# Функция для вывода списка студентов в виде таблицы
# def - ключевое слово для объявления функции в Python
# print_students - название функции (может быть любым понятным именем)
# students - параметр функции, принимающий список студентов
# Аналогичная реализация: def my_function(parameter): ...
def print_students(students):
    print(u"Имя".ljust(15), u"Фамилия".ljust(10), u"Экзамены".ljust(30), u"Оценки".ljust(20))

    for student in students:
        print(student["name"].ljust(15), student["surname"].ljust(10), str(student["exams"]).ljust(30), str(student["marks"]).ljust(20))


# Функция для расчета среднего балла студента
# Принимает список оценок и возвращает среднее арифметическое
# Аналогичная реализация: def calculate(numbers): return sum(numbers) / len(numbers)
def calculate_average(marks):
    # sum(marks) - встроенная функция Python, вычисляющая сумму всех элементов списка
    # len(marks) - встроенная функция Python, возвращающая количество элементов в списке
    # Деление суммы на количество дает среднее арифметическое
    # Аналогичная реализация: sum([1, 2, 3]) вернет 6, len([1, 2, 3]) вернет 3
    total_sum = sum(marks)
    count = len(marks)
    average = total_sum / count
    return average


# Функция для фильтрации студентов по минимальному среднему баллу
# students - список всех студентов
# min_average - минимальный средний балл для фильтрации
# Функция возвращает новый список с отфильтрованными студентами
# Аналогичная реализация: def filter_items(items, condition): ...
def filter_students_by_average(students, min_average):
    # Создаю пустой список для хранения отфильтрованных студентов
    # Аналогичная реализация: result = []
    filtered_students = []
    
    # Перебираю всех студентов в цикле
    for student in students:
        # Получаю список оценок текущего студента
        marks = student["marks"]
        
        # Вычисляю средний балл студента с помощью созданной функции
        average = calculate_average(marks)
        
        # Проверяю, превышает ли средний балл заданный порог
        # Оператор >= означает "больше или равно"
        # Аналогичная реализация: if value >= threshold: ...
        if average >= min_average:
            # Если условие выполняется, добавляю студента в отфильтрованный список
            # Метод append() добавляет элемент в конец списка
            # Аналогичная реализация: my_list.append(new_item)
            filtered_students.append(student)
    
    # Возвращаю список студентов, прошедших фильтрацию
    # return - ключевое слово для возврата значения из функции
    return filtered_students


